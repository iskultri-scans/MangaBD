function makeTimestamp(offsetMs = 0): Timestamp {
  const ms = Date.now() + offsetMs;
  const seconds = Math.floor(ms / 1000);
  const nanoseconds = (ms % 1000) * 1_000_000;
  return new Timestamp(seconds, nanoseconds);
}

